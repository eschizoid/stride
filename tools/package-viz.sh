linux_install() {
  cat <<'SH'
#!/bin/sh
# puts Stride in the desktop's application menu, then starts it: a desktop
# entry under ~/.local/share/applications that runs the launcher beside
# this script, and its icon under ~/.local/share/icons/hicolor. The entry
# names this folder by its absolute path, so run this again after moving it.
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
data="${XDG_DATA_HOME:-$HOME/.local/share}"
mkdir -p "$data/applications" "$data/icons/hicolor/256x256/apps"
cp "$here/stride.png" "$data/icons/hicolor/256x256/apps/stride.png"
# an Exec value is read in two layers. The quoting layer puts a backslash
# before " ` $ and \ inside a quoted argument; the desktop file's string
# layer, read first, then needs every backslash written twice. So \ is
# written as four backslashes, " ` and $ each as two backslashes and the
# character, and % as %%
exec_arg=$(printf '%s' "$here/stride-app" | sed -e 's/\\/\\\\\\\\/g' -e 's/["`$]/\\\\&/g' -e 's/%/%%/g')
while IFS= read -r line; do
  case "$line" in
    Exec=*) printf 'Exec="%s"\n' "$exec_arg" ;;
    *) printf '%s\n' "$line" ;;
  esac
done < "$here/stride.desktop" > "$data/applications/stride.desktop.tmp"
mv "$data/applications/stride.desktop.tmp" "$data/applications/stride.desktop"
if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database "$data/applications" >/dev/null 2>&1 || true
fi
echo "stride: added to the application menu"
exec "$here/stride-app"
SH
}

# cmd misparses labels and goto with LF line endings, so the caller writes
# this with CRLF. The steps carry the macOS launcher's names; Windows has
# no `path` step, since a program started from Explorer inherits the
# user's whole PATH
windows_launcher() {
  cat <<'BAT'
@echo off
rem step: locate
set "here=%~dp0"
rem step: log
set "log=%USERPROFILE%\.stride\seed.log"
rem step: seed-fonts
rem the window reads %USERPROFILE%\.stride\fonts; seed it from the copies
rem shipped beside this script, copying any that are missing or differ in
rem size, so a copy cut short is repaired on the next launch
if not exist "%USERPROFILE%\.stride\fonts" mkdir "%USERPROFILE%\.stride\fonts" >nul 2>&1 || echo %date% %time%: could not create "%USERPROFILE%\.stride\fonts" - the window will use its fallback font>>"%log%" 2>nul
for %%f in ("%here%fonts\*.ttf") do call :seed "%%~ff" fonts
rem step: seed-img
rem the splash's mark and the streak flame render from
rem %USERPROFILE%\.stride\img, seeded the same way
if not exist "%USERPROFILE%\.stride\img" mkdir "%USERPROFILE%\.stride\img" >nul 2>&1 || echo %date% %time%: could not create "%USERPROFILE%\.stride\img" - the splash and the streak chip will show text alone>>"%log%" 2>nul
for %%f in ("%here%img\*.png") do call :seed "%%~ff" img
rem step: home
cd /d "%USERPROFILE%"
rem step: start
rem the athlete's directory first, the window's read-write grant, then
rem the home, the launch directory a capture's status row names its
rem file under
start "" "%here%stride-viz.exe" "%USERPROFILE%\.stride" "%USERPROFILE%"
exit /b 0
:seed
rem every %var% read below sits on its OWN line - cmd expands at
rem parse time per line, so no delayed expansion is needed; folding
rem these into a parenthesized block would break that property
set "src=%~1"
set "dst=%USERPROFILE%\.stride\%~2\%~nx1"
if not exist "%dst%" goto :put
set "ssize=0"
set "dsize=0"
for %%A in ("%src%") do set "ssize=%%~zA"
for %%B in ("%dst%") do set "dsize=%%~zB"
if "%ssize%"=="%dsize%" goto :eof
:put
copy /y "%src%" "%dst%" >nul 2>&1 || echo %date% %time%: could not write "%dst%">>"%log%"
goto :eof
BAT
}

# written with CRLF like the launcher. install.cmd hands it the app's
# folder and the home through the environment, so cmd quotes no path for
# it, whatever characters the folder's name holds, and runs its text as a
# script block, which no execution policy governs, as a script file is
windows_shortcut() {
  cat <<'PS'
# Writes Stride's shortcut into the Start menu (created when absent, and
# required) and onto the Desktop (skipped when that folder is missing). A
# shortcut runs stride-app.bat from this folder through cmd, minimized, in
# the home directory, and shows stride.ico. cmd /c keeps a line whose
# first character is not a quote as it is, so the quoted path after call
# survives any & or parenthesis in it. A failure waits for a key only when
# stdin is a console.
$ErrorActionPreference = 'Stop'
$q = [char]34
$app = $env:STRIDE_APP
$h = $env:USERPROFILE
$target = Join-Path $env:SystemRoot 'System32\cmd.exe'
$arguments = '/d /c call ' + $q + (Join-Path $app 'stride-app.bat') + $q
$w = New-Object -ComObject WScript.Shell
foreach ($f in 'Programs', 'Desktop') {
  $d = ''
  try {
    if ($f -eq 'Programs') { $d = [Environment]::GetFolderPath($f, 'Create') } else { $d = [Environment]::GetFolderPath($f) }
    if (-not $d -or -not (Test-Path -LiteralPath $d)) { throw ('the ' + $f + ' folder does not exist') }
    $s = $w.CreateShortcut((Join-Path $d 'Stride.lnk'))
    $s.TargetPath = $target
    $s.Arguments = $arguments
    $s.WorkingDirectory = $h
    $s.IconLocation = (Join-Path $app 'stride.ico') + ',0'
    $s.WindowStyle = 7
    $s.Description = 'Stride'
    $s.Save()
    Write-Host ('Stride: shortcut written to ' + $d)
  } catch {
    if ($f -eq 'Desktop') {
      Write-Host ('Stride: no Desktop shortcut, skipped: ' + $_.Exception.Message)
      continue
    }
    Write-Host ('Stride: could not write the Start-menu shortcut in ' + $d + ': ' + $_.Exception.Message)
    if (-not [Console]::IsInputRedirected) { [void](Read-Host 'Press Enter to close') }
    throw 'Stride: the Start-menu shortcut was not written'
  }
}
PS
}

# written with CRLF like the launcher
windows_install() {
  cat <<'BAT'
@echo off
rem puts Stride in the Start menu, and on the Desktop when there is one,
rem then seeds the athlete's directory and starts the app through
rem stride-app.bat. The shortcuts name this folder, so run this again
rem after moving it.
setlocal
set "STRIDE_APP=%~dp0"
powershell -NoProfile -Command "$ErrorActionPreference = 'Stop'; & ([scriptblock]::Create((Get-Content -LiteralPath (Join-Path $env:STRIDE_APP 'shortcut.ps1') -Raw)))"
if errorlevel 1 exit /b 1
call "%~dp0stride-app.bat"
BAT
}

crlf() { awk '{ printf "%s\r\n", $0 }'; }

# a shortcut's target, arguments, icon, working directory and window
# style, one per line
lnk_fields() {
  LNK="$1" powershell -NoProfile -Command '$s = (New-Object -ComObject WScript.Shell).CreateShortcut($env:LNK); $s.TargetPath; $s.Arguments; $s.IconLocation; $s.WorkingDirectory; $s.WindowStyle' | tr -d '\r'
}

# the shortcut install.cmd wrote into a folder: it runs the app folder's
# stride-app.bat through cmd, minimized (window style 7), from the home,
# and shows stride.ico. Every argument is a windows path
check_lnk() {
  local name="$1" lnk="$2\\Stride.lnk" app="$3" home="$4" fields target args icon wd style want
  [ -s "$(cygpath -u "$lnk")" ] || { echo "::error::install.cmd wrote no $name shortcut in $2"; exit 1; }
  fields="$(lnk_fields "$lnk")"
  target="$(sed -n 1p <<<"$fields")"; args="$(sed -n 2p <<<"$fields")"
  icon="$(sed -n 3p <<<"$fields")"; wd="$(sed -n 4p <<<"$fields")"; style="$(sed -n 5p <<<"$fields")"
  [[ "${target,,}" == *'\system32\cmd.exe' ]] ||
    { echo "::error::the $name shortcut targets $target, not cmd.exe"; exit 1; }
  want="/d /c call \"$app\\stride-app.bat\""
  [ "$args" = "$want" ] || { echo "::error::the $name shortcut passes $args, not $want"; exit 1; }
  [ "$icon" = "$app\\stride.ico,0" ] || { echo "::error::the $name shortcut's icon is $icon"; exit 1; }
  [ "$wd" = "$home" ] || { echo "::error::the $name shortcut starts in $wd, not $home"; exit 1; }
  [ "$style" = 7 ] || { echo "::error::the $name shortcut's window style is $style, not 7 (minimized)"; exit 1; }
}

# the staged launcher, shortcut script and install step (posix paths). The
# launcher starts one program, the window (check_parity holds its start
# line to the macOS launcher's). The shortcut runs that launcher through
# cmd, minimized, from the home. The install step hands the script its
# folder through the environment and runs the script's text, never the file,
# since an execution policy set by Group Policy blocks a script file whatever
# -ExecutionPolicy says. cmd splits an unquoted path at & and parentheses,
# so in both cmd files no path variable appears outside double quotes.
check_launcher() {
  local bat ps inst k starts f code bare
  bat="$(tr -d '\r' < "$1")"
  ps="$(tr -d '\r' < "$2")"
  inst="$(tr -d '\r' < "$3")"
  starts="$(grep -v '^rem ' <<<"$bat" | grep -ciF 'start ' || true)"
  [ "$starts" = 1 ] || { echo "::error::the launcher has $starts start lines; it must have only the window's"; exit 1; }
  for k in \
    '$app = $env:STRIDE_APP' \
    '$h = $env:USERPROFILE' \
    "\$target = Join-Path \$env:SystemRoot 'System32\\cmd.exe'" \
    "\$arguments = '/d /c call ' + \$q + (Join-Path \$app 'stride-app.bat') + \$q" \
    '    $s.WorkingDirectory = $h' \
    "    \$s.IconLocation = (Join-Path \$app 'stride.ico') + ',0'" \
    '    $s.WindowStyle = 7'; do
    grep -qxF -- "$k" <<<"$ps" || { echo "::error::shortcut.ps1 lacks the line: $k"; exit 1; }
  done
  for k in \
    'set "STRIDE_APP=%~dp0"' \
    "powershell -NoProfile -Command \"\$ErrorActionPreference = 'Stop'; & ([scriptblock]::Create((Get-Content -LiteralPath (Join-Path \$env:STRIDE_APP 'shortcut.ps1') -Raw)))\"" \
    'if errorlevel 1 exit /b 1'; do
    grep -qxF -- "$k" <<<"$inst" || { echo "::error::install.cmd lacks the line: $k"; exit 1; }
  done
  ! grep -qiE -- '-File( |$)' <<<"$inst" || { echo "::error::install.cmd runs a script file, which an execution policy can block"; exit 1; }
  for f in launcher install.cmd; do
    if [ "$f" = launcher ]; then code="$bat"; else code="$inst"; fi
    bare="$(grep -v '^rem ' <<<"$code" | sed -e 's/"[^"]*"//g' | grep -n -E '%(USERPROFILE|here|STRIDE_APP)%|%~dp0' || true)"
    [ -z "$bare" ] || { echo "::error::the $f names a path outside double quotes: $bare"; exit 1; }
  done
}

# runs install.cmd (a windows path) as a fake profile (a posix path) with
# stdin closed, after printing where that profile's Programs and Desktop
# folders resolve; sets $log to what it printed, and fails when it fails
# or does not seed the profile through the launcher
install_as() {
  local fake="$1" install="$2" fakewin
  fakewin="$(cygpath -w "$fake")"
  echo "package-viz: under $fakewin, Programs is '$(folder_of "$fakewin" Programs)' and Desktop is '$(folder_of "$fakewin" Desktop)'"
  log="$(USERPROFILE="$fakewin" cmd //C call "$install" </dev/null 2>&1)" ||
    { printf '%s\n' "$log"; echo "::error::install.cmd failed"; exit 1; }
  printf '%s\n' "$log"
  wait_seeded "$fake"
  taskkill //IM stride-viz.exe //F >/dev/null 2>&1 || true
}

# a special folder as a profile (a windows path) resolves it
folder_of() {
  USERPROFILE="$1" powershell -NoProfile -Command "[Environment]::GetFolderPath('$2')" | tr -d '\r'
}

case "$os $step" in
  "linux package")
    bin="${3:?the linux binary to package}"
    need "$bin" "the linux binary"
    need img/stride-icon-256.png "the linux menu icon"
    need img/stride-icons.sha256 "the icons' pin"
    check_icons
    check_parity
    stage_common
    cp "$bin" stage/stride-app/stride-viz
    cp img/stride-icon-256.png stage/stride-app/stride.png
    linux_launcher > stage/stride-app/stride-app
    linux_install > stage/stride-app/install.sh
    linux_desktop_entry > stage/stride-app/stride.desktop
    check_desktop stage/stride-app/stride.desktop
    chmod +x stage/stride-app/stride-app stage/stride-app/stride-viz stage/stride-app/install.sh
    tar -C stage -czf stride-app-linux-x86_64.tar.gz stride-app
    # shellcheck disable=SC2046
    assert_listing "$(tar -tzf stride-app-linux-x86_64.tar.gz)" stride-viz stride-app install.sh stride.desktop stride.png $(carried)
    out="$(mktemp -d)"
    tar -xzf stride-app-linux-x86_64.tar.gz -C "$out"
    check_fonts_dir "$out/stride-app/fonts"
    ;;
  "windows package")
    bin="${3:?the windows binary to package}"
    need "$bin" "the windows binary"
    need img/stride.ico "the windows shortcut icon"
    need img/stride-icon-256.png "the icon's 256 px image"
    need img/stride-icons.sha256 "the icons' pin"
    check_icons
    check_ico img/stride.ico
    check_parity
    stage_common
    cp "$bin" stage/stride-app/stride-viz.exe
    cp img/stride.ico stage/stride-app/stride.ico
    windows_launcher | crlf > stage/stride-app/stride-app.bat
    windows_shortcut | crlf > stage/stride-app/shortcut.ps1
    windows_install | crlf > stage/stride-app/install.cmd
    check_launcher stage/stride-app/stride-app.bat stage/stride-app/shortcut.ps1 stage/stride-app/install.cmd
    rm -f stride-app-windows-x86_64.zip
    7z a -bso0 stride-app-windows-x86_64.zip ./stage/stride-app
    # shellcheck disable=SC2046
    assert_listing "$(7z l stride-app-windows-x86_64.zip)" stride-viz.exe stride-app.bat shortcut.ps1 install.cmd stride.ico $(carried)
    out="$(mktemp -d)"
    7z x -bso0 stride-app-windows-x86_64.zip -o"$out"
    check_fonts_dir "$out/stride-app/fonts"
    ;;
  "macos verify")
    # the bundle tools/make-viz-app.sh built (a posix path to Stride.app)
    app="${3:?the Stride.app to verify}"
    check_parity
    check_fonts_dir "$app/Contents/Resources/fonts"
    for f in $images; do
      cmp -s "img/$f" "$app/Contents/Resources/img/$f" || { echo "::error::the bundle does not carry img/$f"; exit 1; }
    done
    ;;
  "macos prove")
    app="${3:?the Stride.app to prove}"
    fake="$(mktemp -d)"
    HOME="$fake" "$app/Contents/MacOS/launcher" >/dev/null 2>&1 &
    pid=$!
    wait_seeded "$fake"
    stop "$pid"
    printf 'x' > "$fake/.stride/fonts/Quicksand-Medium.ttf"
    printf 'x' > "$fake/.stride/img/flame.png"
    HOME="$fake" "$app/Contents/MacOS/launcher" >/dev/null 2>&1 &
    pid=$!
    wait_seeded "$fake"
    stop "$pid"
    rm -rf "$fake"
    ;;
  "linux prove")
    fake="$(mktemp -d)"
    HOME="$fake" ./stage/stride-app/stride-app >/dev/null 2>&1 &
    pid=$!
    wait_seeded "$fake"
    stop "$pid"
    printf 'x' > "$fake/.stride/fonts/Quicksand-Medium.ttf"
    printf 'x' > "$fake/.stride/img/flame.png"
    HOME="$fake" ./stage/stride-app/stride-app >/dev/null 2>&1 &
    pid=$!
    wait_seeded "$fake"
    stop "$pid"
    rm -rf "$fake"

    # the install step, from a folder whose path needs every Exec escape: a
    # space, a double quote, a backtick, a dollar sign, a percent sign and a
    # backslash
    fake="$(mktemp -d)"
    dir="$fake/"'my "apps" `x` $5 100% a\b'
    mkdir -p "$dir"
    cp -R stage/stride-app "$dir/"
    HOME="$fake" XDG_DATA_HOME="" "$dir/stride-app/install.sh" >/dev/null 2>&1 &
    pid=$!
    wait_seeded "$fake"
    stop "$pid"
    entry="$fake/.local/share/applications/stride.desktop"
    [ -s "$entry" ] || { echo "::error::install.sh wrote no desktop entry"; exit 1; }
    check_desktop "$entry"
    want='Exec="'"$fake"'/my \\"apps\\" \\`x\\` \\$5 100%% a\\\\b/stride-app/stride-app"'
    got=$(grep '^Exec=' "$entry")
    [ "$got" = "$want" ] || { echo "::error::install.sh wrote $got, not $want"; exit 1; }
    argv0=$(exec_argv0 "${got#Exec=}") || { echo "::error::$got does not read as one argument"; exit 1; }
    [ "$argv0" = "$dir/stride-app/stride-app" ] ||
      { echo "::error::$got reads as $argv0, not $dir/stride-app/stride-app"; exit 1; }
    cmp -s img/stride-icon-256.png "$fake/.local/share/icons/hicolor/256x256/apps/stride.png" ||
      { echo "::error::install.sh did not place the menu icon"; exit 1; }
    rm -rf "$fake"
    ;;
  "windows prove")
    # the GitHub windows runner has no OpenGL context, so whether the window starts there is not deterministic; that is verified on a real machine
    fake="$(mktemp -d)"
    fakewin="$(cygpath -w "$fake")"
    bat="$(cygpath -w "$PWD/stage/stride-app/stride-app.bat")"
    USERPROFILE="$fakewin" cmd //C "$bat" </dev/null || true
    wait_seeded "$fake"
    taskkill //IM stride-viz.exe //F >/dev/null 2>&1 || true
    printf 'x' > "$fake/.stride/fonts/Quicksand-Medium.ttf"
    printf 'x' > "$fake/.stride/img/flame.png"
    USERPROFILE="$fakewin" cmd //C "$bat" </dev/null || true
    wait_seeded "$fake"
    taskkill //IM stride-viz.exe //F >/dev/null 2>&1 || true

    # the install step from a folder whose path cmd splits when unquoted
    app="$PWD/stage/R&D (x) y"
    rm -rf "$app"
    mkdir -p "$app"
    cp -R stage/stride-app "$app/"
    appwin="$(cygpath -w "$app/stride-app")"

    # a profile with a Desktop: both shortcuts
    withdesk="$(mktemp -d)"
    mkdir -p "$withdesk/Desktop"
    home="$(cygpath -w "$withdesk")"
    install_as "$withdesk" "$appwin\\install.cmd"
    programs="$(folder_of "$home" Programs)"
    desktop="$(folder_of "$home" Desktop)"
    [ -n "$programs" ] || { echo "::error::install.cmd left no Start-menu folder"; exit 1; }
    [ "$desktop" = "$home\\Desktop" ] ||
      { echo "::error::the profile's Desktop resolves to '$desktop', not $home\\Desktop, so the Desktop shortcut goes unchecked"; exit 1; }
    check_lnk Start-menu "$programs" "$appwin" "$home"
    check_lnk Desktop "$desktop" "$appwin" "$home"

    # a profile without one: the Start-menu shortcut alone, and a note
    nodesk="$(mktemp -d)"
    install_as "$nodesk" "$appwin\\install.cmd"
    check_lnk Start-menu "$(folder_of "$(cygpath -w "$nodesk")" Programs)" "$appwin" "$(cygpath -w "$nodesk")"
    grep -q "no Desktop shortcut, skipped" <<<"$log" ||
      { echo "::error::install.cmd did not report the missing Desktop folder"; exit 1; }
    [ ! -e "$nodesk/Desktop/Stride.lnk" ] || { echo "::error::install.cmd wrote a Desktop it reported missing"; exit 1; }
    ;;
  *)
    echo "usage: package-viz.sh linux|windows package <binary> | linux|windows prove | macos verify|prove <Stride.app>" >&2
    exit 2
    ;;
esac
echo "package-viz: $os $step ok"
