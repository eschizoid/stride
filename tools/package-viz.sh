#!/usr/bin/env bash
# Packages the window for linux and windows, the two platforms with no bundle
# format, and proves each package. The release workflow ships what this builds,
# and build.yml runs the same steps on every pull request, so a package that
# lacks a file the window reads, or a file that puts the app in the system's
# menu, fails before a release carries it.
#
#   package-viz.sh linux package <stride-viz binary>   -> stride-app-linux-x86_64.tar.gz
#   package-viz.sh windows package <stride-viz.exe>    -> stride-app-windows-x86_64.zip
#   package-viz.sh linux prove                         -> launcher and install step, fresh homes
#   package-viz.sh windows prove
#
# Run from the repository root. A package holds the binary, the brand fonts,
# the splash's mark and the streak flame, a launcher, an install step and an
# icon. The launcher seeds the fonts into ~/.stride/fonts and the images into
# ~/.stride/img, where the window reads them, then starts the window from the
# home directory with the athlete's directory as its first argument. The
# install step puts the app in the system's menu with its icon and starts it:
# on linux a desktop entry under ~/.local/share/applications and the icon
# under ~/.local/share/icons/hicolor; on windows a Start-menu and a Desktop
# shortcut carrying stride.ico. The icons are committed and regenerated by
# img/make-icons.sh.
#
# `package` stages under stage/stride-app (git-ignored: `prove` runs from it in
# a later step), archives it with stride-app/ at the archive's root, and fails
# when an input is missing, when the icon or desktop entry is malformed, or
# when the archive lacks any file listed above. `prove` runs the staged
# launcher against an empty home, checks that every face and image arrives,
# truncates one of each and checks that the next launch repairs them; then it
# runs the install step against another empty home and checks the menu entry,
# its icon, and that the entry starts the launcher.
set -euo pipefail

faces="Quicksand-Medium.ttf JetBrainsMono-Regular.ttf"
images="stride-icon.png flame.png"

[ -f src/viz/main.roc ] || { echo "package-viz: run from the repository root" >&2; exit 2; }
os="${1:-}"
step="${2:-}"

# every input this script reads, by name, before anything reads it
need() {
  [ -s "$1" ] || { echo "::error::package-viz: $2 is missing or empty: $1" >&2; exit 1; }
}

stage_common() {
  for f in $faces; do need "assets/fonts/$f" "a face the window loads"; done
  for f in $images; do need "img/$f" "an image the window loads"; done
  rm -rf stage/stride-app
  mkdir -p stage/stride-app/fonts stage/stride-app/img
  cp assets/fonts/*.ttf assets/fonts/OFL-*.txt stage/stride-app/fonts/
  for f in $images; do cp "img/$f" stage/stride-app/img/; done
}

# every path the archive must hold, given the archiver's listing: each must
# end a line under stride-app/. 7z prints CRLF lines on windows, so carriage
# returns are dropped first; a listing in a variable keeps grep -q off a pipe
# that pipefail would fail on SIGPIPE; and each slash becomes a dot in the
# pattern, which matches the backslash 7z prints on windows as well
assert_listing() {
  listing="${1//$'\r'/}"; shift
  for p in "$@"; do
    grep -q "stride-app.${p//\//.}\$" <<<"$listing" || { echo "::error::the archive does not carry stride-app/$p"; exit 1; }
  done
}

# the archive paths every package carries besides its own files
carried() {
  for f in $faces; do echo "fonts/$f"; done
  for f in $images; do echo "img/$f"; done
}

# every face and image in the home given, byte for byte as shipped
check_seeded() {
  for f in $faces; do
    cmp -s "assets/fonts/$f" "$1/.stride/fonts/$f" || { echo "::error::launcher did not seed fonts/$f"; exit 1; }
  done
  for f in $images; do
    cmp -s "img/$f" "$1/.stride/img/$f" || { echo "::error::launcher did not seed img/$f"; exit 1; }
  done
}

# waits up to 20 s for check_seeded to hold in the home given, then runs it
# once more so a failure names the file
wait_seeded() {
  for _ in $(seq 20); do
    ( check_seeded "$1" ) >/dev/null 2>&1 && return 0
    sleep 1
  done
  check_seeded "$1"
}

# ends a launch started in the background, and reaps it quietly
stop() {
  kill "$1" 2>/dev/null || true
  wait "$1" 2>/dev/null || true
}

# the unsigned little-endian integer of $3 bytes at offset $2 in file $1
le() {
  od -An -tu1 -j "$2" -N "$3" "$1" | awk '{ for (i = NF; i >= 1; i--) v = v * 256 + $i } END { print v + 0 }'
}

# an ICO whose header is an icon directory, whose every entry points at a
# PNG inside the file, which holds a 256 px image, and whose 256 px image is
# the linux icon byte for byte, so the two icons cannot drift apart
check_ico() {
  local ico="$1" size n big e len off sig i
  size=$(wc -c < "$ico" | tr -d ' ')
  [ "$(le "$ico" 0 2)" = 0 ] && [ "$(le "$ico" 2 2)" = 1 ] || { echo "::error::$ico is not an icon file"; exit 1; }
  n=$(le "$ico" 4 2)
  [ "$n" -gt 0 ] || { echo "::error::$ico holds no image"; exit 1; }
  big=""
  for i in $(seq 0 $((n - 1))); do
    e=$((6 + 16 * i))
    len=$(le "$ico" $((e + 8)) 4)
    off=$(le "$ico" $((e + 12)) 4)
    [ $((off + len)) -le "$size" ] || { echo "::error::$ico entry $i points past the end of the file"; exit 1; }
    sig=$(od -An -tx1 -j "$off" -N 8 "$ico" | tr -d ' \n')
    [ "$sig" = 89504e470d0a1a0a ] || { echo "::error::$ico entry $i is not a PNG"; exit 1; }
    [ "$(le "$ico" "$e" 1)" = 0 ] && big="$off $len"
  done
  [ -n "$big" ] || { echo "::error::$ico has no 256 px image"; exit 1; }
  set -- $big
  tail -c +$(($1 + 1)) "$ico" | head -c "$2" | cmp -s - img/stride-icon-256.png ||
    { echo "::error::$ico's 256 px image is not img/stride-icon-256.png; rerun img/make-icons.sh"; exit 1; }
}

# the window's title, which X11 reports as its WM_CLASS; a desktop entry's
# StartupWMClass must equal it for a dock to show the entry's icon on the
# running window
window_title() {
  local t; t=$(sed -n 's/.*\.with_title("\([^"]*\)").*/\1/p' src/viz/main.roc | head -1)
  [ -n "$t" ] || { echo "::error::src/viz/main.roc sets no window title" >&2; exit 1; }
  printf '%s' "$t"
}

# a desktop entry with every key the menu and the dock read
check_desktop() {
  local entry kv title; entry="$(cat "$1")"
  # a substitution inside a word list would swallow window_title's exit
  title=$(window_title)
  for kv in "[Desktop Entry]" "Type=Application" "Name=Stride" "Icon=stride" "Terminal=false" "StartupWMClass=$title"; do
    grep -qxF "$kv" <<<"$entry" || { echo "::error::$1 lacks the line $kv"; exit 1; }
  done
  grep -q '^Exec=.' <<<"$entry" || { echo "::error::$1 has no Exec line"; exit 1; }
}

linux_launcher() {
  cat <<'SH'
#!/bin/sh
# a desktop launch inherits a minimal PATH, and the window runs `stride`
# for the CP fit and `sh` for the zone offset. It also passes the athlete's
# directory, the window's read-write grant (a home resolved at launch cannot
# be written into the source the grant is declared in), and the home as the
# launch directory a capture's status row names its file under.
PATH="$HOME/.local/bin:/usr/local/bin:$PATH"
export PATH
# the window reads ~/.stride/fonts; seed it from the copies shipped
# beside this script, replacing any that differ in size
here="$(cd "$(dirname "$0")" && pwd)"
log="$HOME/.stride/seed.log"
if [ -d "$here/fonts" ]; then
  if mkdir -p "$HOME/.stride/fonts" 2>/dev/null; then
    for f in "$here"/fonts/*.ttf; do
      [ -e "$f" ] || continue
      dst="$HOME/.stride/fonts/$(basename "$f")"
      if [ ! -e "$dst" ] || [ "$(wc -c < "$f")" != "$(wc -c < "$dst")" ]; then
        cp "$f" "$dst" 2>>"$log" || echo "$(date): could not write $dst" >> "$log"
      fi
    done
  else
    echo "$(date): could not create $HOME/.stride/fonts - the window will use its fallback font" >> "$log" 2>/dev/null || true
  fi
fi
# the splash's mark and the streak flame render from ~/.stride/img,
# seeded the same way
if [ -d "$here/img" ]; then
  if mkdir -p "$HOME/.stride/img" 2>/dev/null; then
    for f in "$here"/img/*.png; do
      [ -e "$f" ] || continue
      dst="$HOME/.stride/img/$(basename "$f")"
      if [ ! -e "$dst" ] || [ "$(wc -c < "$f")" != "$(wc -c < "$dst")" ]; then
        cp "$f" "$dst" 2>>"$log" || echo "$(date): could not write $dst" >> "$log"
      fi
    done
  else
    echo "$(date): could not create $HOME/.stride/img - the splash and the streak chip will show text alone" >> "$log" 2>/dev/null || true
  fi
fi
cd "$HOME"
exec "$here/stride-viz" "$HOME/.stride" "$HOME"
SH
}

# the Exec line is a placeholder: install.sh writes the launcher's absolute
# path, which only the athlete's machine knows
linux_desktop_entry() {
  cat <<DESKTOP
[Desktop Entry]
Type=Application
Name=Stride
Comment=Training dashboard over the stride database
Exec=stride-app
Icon=stride
Terminal=false
Categories=Utility;
StartupWMClass=$(window_title)
DESKTOP
}

linux_install() {
  cat <<'SH'
#!/bin/sh
# puts Stride in the desktop's application menu, then starts it: a desktop
# entry under ~/.local/share/applications that runs the launcher beside
# this script, and its icon under ~/.local/share/icons/hicolor. The entry
# names this folder by its absolute path, so run this again after moving it.
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
data="${XDG_DATA_HOME:-$HOME/.local/share}"
mkdir -p "$data/applications" "$data/icons/hicolor/256x256/apps"
cp "$here/stride.png" "$data/icons/hicolor/256x256/apps/stride.png"
# a quoted Exec argument escapes " ` $ and \ with a backslash, a desktop
# file's string rules then double every backslash, and % is written %%
exec_arg=$(printf '%s' "$here/stride-app" | sed -e 's/\\/\\\\\\\\/g' -e 's/["`$]/\\&/g' -e 's/%/%%/g')
while IFS= read -r line; do
  case "$line" in
    Exec=*) printf 'Exec="%s"\n' "$exec_arg" ;;
    *) printf '%s\n' "$line" ;;
  esac
done < "$here/stride.desktop" > "$data/applications/stride.desktop.tmp"
mv "$data/applications/stride.desktop.tmp" "$data/applications/stride.desktop"
if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database "$data/applications" >/dev/null 2>&1 || true
fi
echo "stride: added to the application menu"
exec "$here/stride-app"
SH
}

# cmd misparses labels and goto with LF line endings, so the caller writes
# this with CRLF
windows_launcher() {
  cat <<'BAT'
@echo off
rem stride-viz.exe is a console program, so a console opened for it stays
rem open behind its window. Started any other way than with the argument
rem headless, this script starts itself again under a console host with
rem no window, passing headless, and exits. The shortcuts install.cmd
rem writes start it the same way.
if /i not "%~1"=="headless" (
  start "" "%SystemRoot%\System32\conhost.exe" --headless "%ComSpec%" /d /c call "%~f0" headless
  exit /b 0
)
rem the window reads %USERPROFILE%\.stride\fonts and, for the splash's
rem mark and the streak flame, %USERPROFILE%\.stride\img; seed each from
rem the copies shipped beside this script, replacing any that differ in
rem size, then start the window from the home directory
set "here=%~dp0"
set "log=%USERPROFILE%\.stride\seed.log"
if not exist "%USERPROFILE%\.stride\fonts" mkdir "%USERPROFILE%\.stride\fonts" >nul 2>&1
for %%f in ("%here%fonts\*.ttf") do call :seed "%%~ff" fonts
if not exist "%USERPROFILE%\.stride\img" mkdir "%USERPROFILE%\.stride\img" >nul 2>&1
for %%f in ("%here%img\*.png") do call :seed "%%~ff" img
cd /d "%USERPROFILE%"
"%here%stride-viz.exe" "%USERPROFILE%\.stride" "%USERPROFILE%"
exit /b 0
:seed
rem every %var% read below sits on its OWN line - cmd expands at
rem parse time per line, so no delayed expansion is needed; folding
rem these into a parenthesized block would break that property
set "src=%~1"
set "dst=%USERPROFILE%\.stride\%~2\%~nx1"
if not exist "%dst%" goto :put
set "ssize=0"
set "dsize=0"
for %%A in ("%src%") do set "ssize=%%~zA"
for %%B in ("%dst%") do set "dsize=%%~zB"
if "%ssize%"=="%dsize%" goto :eof
:put
copy /y "%src%" "%dst%" >nul 2>&1 || echo %date% %time%: could not write "%dst%">>"%log%"
goto :eof
BAT
}

# written with CRLF like the launcher. The shortcuts start the launcher
# through a console host with no window, carry stride.ico, and name this
# folder by its absolute path. PowerShell writes them, reading every value
# from the environment so no path is quoted twice. A special folder can
# resolve to an empty path or a missing directory (a redirected or absent
# Desktop, for one), so each is checked before use: the Start-menu folder
# is created when absent and its shortcut is required; a Desktop that
# cannot take one is reported and skipped. A failure waits for a key only
# when stdin is a console, so a run without one never blocks.
windows_install() {
  cat <<'BAT'
@echo off
rem puts Stride in the Start menu, and on the Desktop when there is one,
rem then starts it. Each shortcut shows stride.ico and runs stride-app.bat
rem from this folder, so run this again after moving the folder.
setlocal
set "here=%~dp0"
set "STRIDE_LNK_TARGET=%SystemRoot%\System32\conhost.exe"
set "STRIDE_LNK_ARGS=--headless "%ComSpec%" /d /c call "%here%stride-app.bat" headless"
set "STRIDE_LNK_ICON=%here%stride.ico,0"
set "STRIDE_LNK_HOME=%USERPROFILE%"
powershell -NoProfile -ExecutionPolicy Bypass -Command "$ErrorActionPreference = 'Stop'; $w = New-Object -ComObject WScript.Shell; foreach ($f in 'Programs', 'Desktop') { try { if ($f -eq 'Programs') { $d = [Environment]::GetFolderPath($f, 'Create') } else { $d = [Environment]::GetFolderPath($f) }; if (-not $d -or -not (Test-Path -LiteralPath $d)) { throw ('the ' + $f + ' folder does not exist') }; $s = $w.CreateShortcut((Join-Path $d 'Stride.lnk')); $s.TargetPath = $env:STRIDE_LNK_TARGET; $s.Arguments = $env:STRIDE_LNK_ARGS; $s.WorkingDirectory = $env:STRIDE_LNK_HOME; $s.IconLocation = $env:STRIDE_LNK_ICON; $s.Description = 'Stride'; $s.Save(); Write-Host ('Stride: shortcut written to ' + $d) } catch { if ($f -eq 'Programs') { Write-Host ('Stride: could not write the Start-menu shortcut: ' + $_.Exception.Message); if (-not [Console]::IsInputRedirected) { [void](Read-Host 'Press Enter to close') }; exit 1 }; Write-Host ('Stride: no Desktop shortcut, skipped: ' + $_.Exception.Message) } }"
if errorlevel 1 exit /b 1
call "%here%stride-app.bat"
BAT
}

crlf() { awk '{ printf "%s\r\n", $0 }'; }

# a shortcut's target, arguments and icon, one per line
lnk_fields() {
  LNK="$1" powershell -NoProfile -Command '$s = (New-Object -ComObject WScript.Shell).CreateShortcut($env:LNK); $s.TargetPath; $s.Arguments; $s.IconLocation' | tr -d '\r'
}

# the shortcut install.cmd wrote into the folder given (a windows path):
# it starts the staged launcher through conhost and shows stride.ico
check_lnk() {
  local name="$1" lnk="$2\\Stride.lnk" stage fields target args icon
  stage="$(cygpath -w "$PWD/stage/stride-app")"
  [ -s "$(cygpath -u "$lnk")" ] || { echo "::error::install.cmd wrote no $name shortcut in $2"; exit 1; }
  fields="$(lnk_fields "$lnk")"
  target="$(sed -n 1p <<<"$fields")"; args="$(sed -n 2p <<<"$fields")"; icon="$(sed -n 3p <<<"$fields")"
  [[ "${target,,}" == *'\system32\conhost.exe' ]] ||
    { echo "::error::the $name shortcut targets $target, not conhost.exe"; exit 1; }
  [[ "$args" == "--headless "*" /d /c call \"$stage\\stride-app.bat\" headless" ]] ||
    { echo "::error::the $name shortcut passes $args"; exit 1; }
  [ "$icon" = "$stage\\stride.ico,0" ] || { echo "::error::the $name shortcut's icon is $icon"; exit 1; }
}

case "$os $step" in
  "linux package")
    bin="${3:?the linux binary to package}"
    need "$bin" "the linux binary"
    need img/stride-icon-256.png "the linux menu icon"
    stage_common
    cp "$bin" stage/stride-app/stride-viz
    cp img/stride-icon-256.png stage/stride-app/stride.png
    linux_launcher > stage/stride-app/stride-app
    linux_install > stage/stride-app/install.sh
    linux_desktop_entry > stage/stride-app/stride.desktop
    check_desktop stage/stride-app/stride.desktop
    chmod +x stage/stride-app/stride-app stage/stride-app/stride-viz stage/stride-app/install.sh
    tar -C stage -czf stride-app-linux-x86_64.tar.gz stride-app
    # shellcheck disable=SC2046
    assert_listing "$(tar -tzf stride-app-linux-x86_64.tar.gz)" stride-viz stride-app install.sh stride.desktop stride.png $(carried)
    ;;
  "windows package")
    bin="${3:?the windows binary to package}"
    need "$bin" "the windows binary"
    need img/stride.ico "the windows shortcut icon"
    need img/stride-icon-256.png "the icon's 256 px image"
    check_ico img/stride.ico
    stage_common
    cp "$bin" stage/stride-app/stride-viz.exe
    cp img/stride.ico stage/stride-app/stride.ico
    windows_launcher | crlf > stage/stride-app/stride-app.bat
    windows_install | crlf > stage/stride-app/install.cmd
    rm -f stride-app-windows-x86_64.zip
    7z a -bso0 stride-app-windows-x86_64.zip ./stage/stride-app
    # shellcheck disable=SC2046
    assert_listing "$(7z l stride-app-windows-x86_64.zip)" stride-viz.exe stride-app.bat install.cmd stride.ico $(carried)
    ;;
  "linux prove")
    fake="$(mktemp -d)"
    HOME="$fake" ./stage/stride-app/stride-app >/dev/null 2>&1 &
    pid=$!
    wait_seeded "$fake"
    stop "$pid"
    printf 'x' > "$fake/.stride/fonts/Quicksand-Medium.ttf"
    printf 'x' > "$fake/.stride/img/flame.png"
    HOME="$fake" ./stage/stride-app/stride-app >/dev/null 2>&1 &
    pid=$!
    wait_seeded "$fake"
    stop "$pid"
    rm -rf "$fake"

    # the install step, from a folder whose path needs every Exec escape: a
    # space, a double quote, a backtick, a dollar sign, a percent sign and a
    # backslash
    fake="$(mktemp -d)"
    dir="$fake/"'my "apps" `x` $5 100% a\b'
    mkdir -p "$dir"
    cp -R stage/stride-app "$dir/"
    HOME="$fake" XDG_DATA_HOME="" "$dir/stride-app/install.sh" >/dev/null 2>&1 &
    pid=$!
    wait_seeded "$fake"
    stop "$pid"
    entry="$fake/.local/share/applications/stride.desktop"
    [ -s "$entry" ] || { echo "::error::install.sh wrote no desktop entry"; exit 1; }
    check_desktop "$entry"
    want='Exec="'"$fake"'/my \"apps\" \`x\` \$5 100%% a\\\\b/stride-app/stride-app"'
    got=$(grep '^Exec=' "$entry")
    [ "$got" = "$want" ] || { echo "::error::install.sh wrote $got, not $want"; exit 1; }
    cmp -s img/stride-icon-256.png "$fake/.local/share/icons/hicolor/256x256/apps/stride.png" ||
      { echo "::error::install.sh did not place the menu icon"; exit 1; }
    rm -rf "$fake"
    ;;
  "windows prove")
    fake="$(mktemp -d)"
    fakewin="$(cygpath -w "$fake")"
    bat="$(cygpath -w "$PWD/stage/stride-app/stride-app.bat")"
    # seeding runs only in the launcher's windowless second start, so a
    # seeded home proves that start happened
    USERPROFILE="$fakewin" cmd //C "$bat" || true
    wait_seeded "$fake"
    taskkill //IM stride-viz.exe //F 2>/dev/null || true
    printf 'x' > "$fake/.stride/fonts/Quicksand-Medium.ttf"
    printf 'x' > "$fake/.stride/img/flame.png"
    USERPROFILE="$fakewin" cmd //C "$bat" || true
    wait_seeded "$fake"
    taskkill //IM stride-viz.exe //F 2>/dev/null || true

    # the install step, under a fake profile. Each special folder is
    # resolved under the same environment install.cmd runs in, and printed
    fake="$(mktemp -d)"
    fakewin="$(cygpath -w "$fake")"
    folder_of() { USERPROFILE="$fakewin" powershell -NoProfile -Command "[Environment]::GetFolderPath('$1')" | tr -d '\r'; }
    desktop="$(folder_of Desktop)"
    echo "package-viz: before install, Programs is '$(folder_of Programs)' and Desktop is '$desktop'"
    log="$(USERPROFILE="$fakewin" cmd //C "$(cygpath -w "$PWD/stage/stride-app/install.cmd")" </dev/null 2>&1)" ||
      { printf '%s\n' "$log"; echo "::error::install.cmd failed"; exit 1; }
    printf '%s\n' "$log"
    wait_seeded "$fake"
    taskkill //IM stride-viz.exe //F 2>/dev/null || true
    programs="$(folder_of Programs)"
    [ -n "$programs" ] || { echo "::error::install.cmd left no Start-menu folder"; exit 1; }
    check_lnk Start-menu "$programs"
    if [ -n "$desktop" ] && [ -d "$(cygpath -u "$desktop")" ]; then
      check_lnk Desktop "$desktop"
    else
      grep -q "no Desktop shortcut, skipped" <<<"$log" ||
        { echo "::error::install.cmd did not report the missing Desktop folder"; exit 1; }
      echo "package-viz: no Desktop folder under the fake profile; install.cmd skipped it and succeeded"
    fi
    # the Start-menu shortcut starts the launcher: a fresh home gets seeded
    fake="$(mktemp -d)"
    USERPROFILE="$(cygpath -w "$fake")" cmd //C start "" "$programs\\Stride.lnk" </dev/null || true
    wait_seeded "$fake"
    taskkill //IM stride-viz.exe //F 2>/dev/null || true
    for dir in "$programs" "$desktop"; do
      [ -n "$dir" ] && rm -f "$(cygpath -u "$dir")/Stride.lnk"
    done
    ;;
  *)
    echo "usage: package-viz.sh linux|windows package <binary> | linux|windows prove" >&2
    exit 2
    ;;
esac
echo "package-viz: $os $step ok"
