    withdesk="$(mktemp -d)"
    mkdir -p "$withdesk/Desktop"
    home="$(cygpath -w "$withdesk")"
    install_as "$withdesk" "$appwin\\install.cmd"
    programs="$(folder_of "$home" Programs)"
    desktop="$(folder_of "$home" Desktop)"
    [ -n "$programs" ] || { echo "::error::install.cmd left no Start-menu folder"; exit 1; }
    [ "$desktop" = "$home\\Desktop" ] ||
      { echo "::error::the profile's Desktop resolves to '$desktop', not $home\\Desktop, so the Desktop shortcut goes unchecked"; exit 1; }
    check_lnk Start-menu "$programs" "$appwin" "$home"
    check_lnk Desktop "$desktop" "$appwin" "$home"

    # a profile without one: the Start-menu shortcut alone, and a note
    nodesk="$(mktemp -d)"
    install_as "$nodesk" "$appwin\\install.cmd"
    check_lnk Start-menu "$(folder_of "$(cygpath -w "$nodesk")" Programs)" "$appwin" "$(cygpath -w "$nodesk")"
    grep -q "no Desktop shortcut, skipped" <<<"$log" ||
      { echo "::error::install.cmd did not report the missing Desktop folder"; exit 1; }
    [ ! -e "$nodesk/Desktop/Stride.lnk" ] || { echo "::error::install.cmd wrote a Desktop it reported missing"; exit 1; }

    # both installs put the package's bin on the user's PATH, once, and a
    # shell that reads its PATH from the registry, as a new terminal does,
    # runs the package's command by name
    n="$(user_path | grep -cixF -- "$appwin\\bin" || true)"
    [ "$n" = 1 ] || { echo "::error::the user's PATH names $appwin\\bin $n times after two installs, not once"; exit 1; }
    fresh="$(powershell -NoProfile -Command "\$env:Path = [Environment]::GetEnvironmentVariable('Path', 'Machine') + ';' + [Environment]::GetEnvironmentVariable('Path', 'User'); (Get-Command stride -CommandType Application | Select-Object -First 1).Path; & stride --version" | tr -d '\r')"
    want=$(source_version)
    [ "$(sed -n 1p <<<"$fresh")" = "$appwin\\bin\\stride.exe" ] && [ "$(sed -n 2p <<<"$fresh")" = "stride $want" ] ||
      { echo "::error::a new shell finds stride as '$fresh', not $appwin\\bin\\stride.exe reporting stride $want"; exit 1; }

    # with STRIDE_APP_START=0 the install step writes the shortcut and
    # starts nothing
    quiet="$(mktemp -d)"
    log="$(USERPROFILE="$(cygpath -w "$quiet")" STRIDE_APP_START=0 cmd //C call "$appwin\\install.cmd" </dev/null 2>&1)" ||
      { printf '%s\n' "$log"; echo "::error::install.cmd failed with STRIDE_APP_START=0"; exit 1; }
    check_lnk Start-menu "$(folder_of "$(cygpath -w "$quiet")" Programs)" "$appwin" "$(cygpath -w "$quiet")"
    [ ! -e "$quiet/.stride" ] || { echo "::error::install.cmd with STRIDE_APP_START=0 started the app"; exit 1; }
    ;;
  *)
    echo "usage: package-viz.sh linux|windows package <window binary> <stride binary> | linux|windows prove | macos verify <Stride.app> <stride binary> | macos prove <Stride.app>" >&2
    exit 2
    ;;
esac
echo "package-viz: $os $step ok"
