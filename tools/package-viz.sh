#!/usr/bin/env bash
# Packages the window for linux and windows, the two platforms with no bundle
# format, and proves each package. The release workflow ships what this builds,
# and build.yml runs the same steps on every pull request, so a package that
# lacks a file the window reads, the command it runs, or a file that puts the
# app in the system's menu, fails before a release carries it.
#
#   package-viz.sh linux package <stride-viz binary> <stride binary>  -> stride-app-linux-x86_64.tar.gz
#   package-viz.sh windows package <stride-viz.exe> <stride.exe>      -> stride-app-windows-x86_64.zip
#   package-viz.sh linux prove                         -> launcher and install step, fresh homes
#   package-viz.sh windows prove
#   package-viz.sh macos verify <Stride.app> <stride binary>  -> the bundle's command, fonts, images and launcher
#   package-viz.sh macos prove <Stride.app>            -> its launcher seeds a fresh home
#
# Run from the repository root. A package holds the binary, the stride
# command from the same build (the release's own CLI asset, byte for byte),
# the brand fonts, the splash's mark and the streak flame, a launcher, an
# install step and an icon. The launcher puts the package's own command first
# on the PATH the window inherits, seeds the fonts into ~/.stride/fonts and
# the images into ~/.stride/img, where the window reads them, then starts the
# window from the home directory with the athlete's directory as its first
# argument. The install step puts the app in the system's menu with its icon
# and the command on the athlete's PATH, then starts the app unless
# STRIDE_APP_START is 0: on linux a desktop entry under
# ~/.local/share/applications, the icon under ~/.local/share/icons/hicolor
# and a link ~/.local/bin/stride when that name is free; on windows a
# Start-menu shortcut and, when that folder exists, a Desktop one, each
# carrying stride.ico, and the package's bin folder on the user's PATH. The
# icons are committed and regenerated by img/make-icons.sh.
#
# `package` stages under stage/stride-app (git-ignored: `prove` runs from it in
# a later step), archives it with stride-app/ at the archive's root, and fails
# when an input is missing, when the command is not the one given or does not
# report the version src/cli/main.roc carries, when the icon or desktop entry
# is malformed, when the windows launcher's start line or shortcut.ps1's
# shortcut fields drift, or when the archive lacks any file listed above.
# `prove` runs the staged launcher against an empty home, checks that every
# face and image arrives, truncates one of each and checks that the next
# launch repairs them, and checks that the launcher finds the package's own
# command before one earlier on the PATH; then it runs the install step
# against fresh homes from a folder whose path needs quoting and checks the
# menu entries, the icon, the command on the PATH and that the launcher
# seeded the home. It does not require the window to start on windows: the
# GitHub windows runner has no OpenGL context, so that is verified on a real
# machine.
set -euo pipefail

faces="Quicksand-Medium.ttf JetBrainsMono-Regular.ttf"
images="stride-icon.png flame.png"

[ -f src/viz/main.roc ] || { echo "package-viz: run from the repository root" >&2; exit 2; }
os="${1:-}"
step="${2:-}"

# every input this script reads, by name, before anything reads it
need() {
  [ -s "$1" ] || { echo "::error::package-viz: $2 is missing or empty: $1" >&2; exit 1; }
}

stage_common() {
  for f in $faces; do need "assets/fonts/$f" "a face the window loads"; done
  for f in $images; do need "img/$f" "an image the window loads"; done
  rm -rf stage/stride-app
  mkdir -p stage/stride-app/fonts stage/stride-app/img
  cp assets/fonts/* stage/stride-app/fonts/
  for f in $images; do cp "img/$f" stage/stride-app/img/; done
}

# every path the archive must hold, given the archiver's listing: each must
# end a line under stride-app/. 7z prints CRLF lines on windows, so carriage
# returns are dropped first; a listing in a variable keeps grep -q off a pipe
# that pipefail would fail on SIGPIPE; and each slash becomes a dot in the
# pattern, which matches the backslash 7z prints on windows as well
assert_listing() {
  listing="${1//$'\r'/}"; shift
  for p in "$@"; do
    grep -q "stride-app.${p//\//.}\$" <<<"$listing" || { echo "::error::the archive does not carry stride-app/$p"; exit 1; }
  done
}

# the archive paths every package carries besides its own files: every file
# in assets/fonts, and the images
carried() {
  for f in assets/fonts/*; do echo "fonts/${f##*/}"; done
  for f in $images; do echo "img/$f"; done
}

# every face in assets/fonts and every image in the home given, byte for
# byte as shipped
check_seeded() {
  for f in assets/fonts/*.ttf; do
    cmp -s "$f" "$1/.stride/fonts/${f##*/}" || { echo "::error::launcher did not seed fonts/${f##*/}"; exit 1; }
  done
  for f in $images; do
    cmp -s "img/$f" "$1/.stride/img/$f" || { echo "::error::launcher did not seed img/$f"; exit 1; }
  done
}

# waits up to 20 s for check_seeded to hold in the home given, then runs it
# once more so a failure names the file
wait_seeded() {
  for _ in $(seq 20); do
    ( check_seeded "$1" ) >/dev/null 2>&1 && return 0
    sleep 1
  done
  check_seeded "$1"
}

# the fonts folder of a package (a posix path) holds exactly the files in
# assets/fonts, byte for byte: none missing, none cut short or stale, none
# extra
check_fonts_dir() {
  local f n
  for f in assets/fonts/*; do
    [ -e "$1/${f##*/}" ] || { echo "::error::$1 lacks fonts/${f##*/}"; exit 1; }
    cmp -s "$f" "$1/${f##*/}" || { echo "::error::$1 holds a fonts/${f##*/} that differs from assets/fonts"; exit 1; }
  done
  for f in "$1"/*; do
    n="${f##*/}"
    [ -e "assets/fonts/$n" ] || { echo "::error::$1 holds fonts/$n, which assets/fonts does not"; exit 1; }
  done
}

# every icon is the one img/make-icons.sh renders from the master: every
# hash in img/stride-icons.sha256 (the master's, the script's, holding each
# platform's transform, and the linux and windows outputs') matches its
# file, and the macOS bundle's iconset is rendered by that script at build
# time, never scaled from a finished image. The script is hashed with
# carriage returns dropped, since a windows checkout may write its lines
# with CRLF; the images are binary and checked out as they are
check_icons() {
  local sum line want file got mva
  if command -v sha256sum >/dev/null 2>&1; then sum="sha256sum"; else sum="shasum -a 256"; fi
  for file in stride-icon.png make-icons.sh stride.ico stride-icon-256.png; do
    line="$(tr -d '\r' < img/stride-icons.sha256 | grep "  $file\$" || true)"
    [ -n "$line" ] || { echo "::error::img/stride-icons.sha256 pins no hash for $file; rerun img/make-icons.sh"; exit 1; }
    want="${line%%  *}"
    case "$file" in
      *.sh) got="$(tr -d '\r' < "img/$file" | $sum | cut -d' ' -f1)" ;;
      *) got="$($sum "img/$file" | cut -d' ' -f1)" ;;
    esac
    [ "$got" = "$want" ] || { echo "::error::img/$file is not the file img/make-icons.sh pinned; rerun img/make-icons.sh"; exit 1; }
  done
  mva="$(tr -d '\r' < tools/make-viz-app.sh)"
  grep -qxF 'sh img/make-icons.sh --iconset "$ICONSET"' <<<"$mva" ||
    { echo "::error::tools/make-viz-app.sh does not render its iconset with img/make-icons.sh"; exit 1; }
  ! grep -qE '^[^#]*sips[^#]*ICONSET' <<<"$mva" ||
    { echo "::error::tools/make-viz-app.sh scales a finished image into its iconset"; exit 1; }
}

# the macOS bundle's launcher, as tools/make-viz-app.sh writes it
mac_launcher() {
  awk '$0 == "cat > \"$C/MacOS/launcher\" <<\x27SH\x27" { on = 1; next } on && $0 == "SH" { exit } on' tools/make-viz-app.sh
}

# the step names a launcher marks, in order, given its text and the
# marker's comment word (# or rem)
steps_of() {
  sed -n "s/^$2 step: \\([a-z-]*\\)\$/\\1/p" <<<"$1" | tr '\n' ' '
}

# the lines of one step, from its marker to the next
step_block() {
  awk -v m="$2 step: $3" -v p="$2 step: " '$0 == m { on = 1; next } index($0, p) == 1 { on = 0 } on' <<<"$1"
}

# every launcher carries the macOS launcher's steps. The linux launcher's
# steps match the macOS one's line for line, except where each finds its
# files and its command; the windows launcher has each step in cmd's terms.
# The `path` step puts the package's own command first on the PATH, so the
# window runs the command from its own build before any other install of
# it; the linux and macOS ones also add the folders a desktop launch leaves
# off a minimal PATH. A step added to the macOS launcher fails here until
# the list below and the other two launchers carry it.
mac_steps="locate path log seed-fonts seed-img home start "
check_parity() {
  local mac linux win s k
  mac="$(mac_launcher)"
  linux="$(linux_launcher)"
  win="$(windows_launcher | tr -d '\r')"
  [ -n "$mac" ] || { echo "::error::tools/make-viz-app.sh writes no launcher this check can find"; exit 1; }
  [ "$(steps_of "$mac" '#')" = "$mac_steps" ] ||
    { echo "::error::the macOS launcher's steps are '$(steps_of "$mac" '#')', not '$mac_steps'"; exit 1; }
  [ "$(steps_of "$linux" '#')" = "$mac_steps" ] ||
    { echo "::error::the linux launcher's steps are '$(steps_of "$linux" '#')', not the macOS launcher's '$mac_steps'"; exit 1; }
  [ "$(steps_of "$win" rem)" = "$mac_steps" ] ||
    { echo "::error::the windows launcher's steps are '$(steps_of "$win" rem)', not the macOS launcher's '$mac_steps'"; exit 1; }
  for s in log seed-fonts seed-img home start; do
    [ "$(step_block "$mac" '#' "$s")" = "$(step_block "$linux" '#' "$s")" ] ||
      { echo "::error::the linux launcher's $s step differs from the macOS launcher's"; exit 1; }
  done
  for k in \
    'locate|here="$(cd "$(dirname "$0")" && pwd)"' \
    'locate|assets="$here/../Resources"' \
    'path|PATH="$here:$HOME/.local/bin:/usr/local/bin:/opt/homebrew/bin:$PATH"' \
    'path|export PATH' \
    'log|log="$HOME/.stride/seed.log"' \
    'seed-fonts|    for f in "$assets"/fonts/*.ttf; do' \
    'seed-fonts|      if [ ! -e "$dst" ] || [ "$(wc -c < "$f")" != "$(wc -c < "$dst")" ]; then' \
    'seed-fonts|        cp "$f" "$dst" 2>>"$log" || echo "$(date): could not write $dst" >> "$log"' \
    'seed-img|    for f in "$assets"/img/*.png; do' \
    'seed-img|      if [ ! -e "$dst" ] || [ "$(wc -c < "$f")" != "$(wc -c < "$dst")" ]; then' \
    'home|cd "$HOME"' \
    'start|exec "$here/stride-viz" "$HOME/.stride" "$HOME"'; do
    grep -qxF -- "${k#*|}" <<<"$(step_block "$mac" '#' "${k%%|*}")" ||
      { echo "::error::the macOS launcher's ${k%%|*} step lacks: ${k#*|}"; exit 1; }
  done
  for k in \
    'locate|here="$(cd "$(dirname "$0")" && pwd)"' \
    'locate|assets="$here"' \
    'path|PATH="$here/bin:$HOME/.local/bin:/usr/local/bin:$PATH"' \
    'path|export PATH'; do
    grep -qxF -- "${k#*|}" <<<"$(step_block "$linux" '#' "${k%%|*}")" ||
      { echo "::error::the linux launcher's ${k%%|*} step lacks: ${k#*|}"; exit 1; }
  done
  for k in \
    'locate|set "here=%~dp0"' \
    'path|set "PATH=%here%bin;%PATH%"' \
    'log|set "log=%USERPROFILE%\.stride\seed.log"' \
    'seed-fonts|for %%f in ("%here%fonts\*.ttf") do call :seed "%%~ff" fonts' \
    'seed-fonts|if not exist "%USERPROFILE%\.stride\fonts" mkdir "%USERPROFILE%\.stride\fonts" >nul 2>&1 || echo %date% %time%: could not create "%USERPROFILE%\.stride\fonts" - the window will use its fallback font>>"%log%" 2>nul' \
    'seed-img|for %%f in ("%here%img\*.png") do call :seed "%%~ff" img' \
    'seed-img|if not exist "%USERPROFILE%\.stride\img" mkdir "%USERPROFILE%\.stride\img" >nul 2>&1 || echo %date% %time%: could not create "%USERPROFILE%\.stride\img" - the splash and the streak chip will show text alone>>"%log%" 2>nul' \
    'home|cd /d "%USERPROFILE%"' \
    'start|start "" "%here%stride-viz.exe" "%USERPROFILE%\.stride" "%USERPROFILE%"'; do
    grep -qxF -- "${k#*|}" <<<"$(step_block "$win" rem "${k%%|*}")" ||
      { echo "::error::the windows launcher's ${k%%|*} step lacks: ${k#*|}"; exit 1; }
  done
  # the repair rule both seeding steps call: copy when the copy is missing
  # or differs in size, and log a copy that fails
  for k in \
    'if not exist "%dst%" goto :put' \
    'for %%A in ("%src%") do set "ssize=%%~zA"' \
    'for %%B in ("%dst%") do set "dsize=%%~zB"' \
    'if "%ssize%"=="%dsize%" goto :eof' \
    'copy /y "%src%" "%dst%" >nul 2>&1 || echo %date% %time%: could not write "%dst%">>"%log%"'; do
    grep -qxF -- "$k" <<<"$win" || { echo "::error::the windows launcher's repair rule lacks: $k"; exit 1; }
  done
}

# ends a launch started in the background, and reaps it quietly
stop() {
  kill "$1" 2>/dev/null || true
  wait "$1" 2>/dev/null || true
}

# the unsigned little-endian integer of $3 bytes at offset $2 in file $1
le() {
  od -An -tu1 -j "$2" -N "$3" "$1" | awk '{ for (i = NF; i >= 1; i--) v = v * 256 + $i } END { print v + 0 }'
}

# an ICO whose header is an icon directory, whose every entry points at a
# PNG inside the file, and which holds the sizes Windows asks an app for at
# the least: 16, 24, 32, 48 and 256 px. Whether its pixels are the source's
# is img/make-icons.sh --check's to say
check_ico() {
  local ico="$1" size n e len off sig i w have want
  size=$(wc -c < "$ico" | tr -d ' ')
  [ "$(le "$ico" 0 2)" = 0 ] && [ "$(le "$ico" 2 2)" = 1 ] || { echo "::error::$ico is not an icon file"; exit 1; }
  n=$(le "$ico" 4 2)
  [ "$n" -gt 0 ] || { echo "::error::$ico holds no image"; exit 1; }
  have=" "
  for i in $(seq 0 $((n - 1))); do
    e=$((6 + 16 * i))
    len=$(le "$ico" $((e + 8)) 4)
    off=$(le "$ico" $((e + 12)) 4)
    [ $((off + len)) -le "$size" ] || { echo "::error::$ico entry $i points past the end of the file"; exit 1; }
    sig=$(od -An -tx1 -j "$off" -N 8 "$ico" | tr -d ' \n')
    [ "$sig" = 89504e470d0a1a0a ] || { echo "::error::$ico entry $i is not a PNG"; exit 1; }
    w=$(le "$ico" "$e" 1)
    [ "$w" = 0 ] && w=256
    have="$have$w "
  done
  for want in 16 24 32 48 256; do
    case "$have" in *" $want "*) ;; *) echo "::error::$ico has no $want px image"; exit 1 ;; esac
  done
}

# the window's title, which X11 reports as its WM_CLASS; a desktop entry's
# StartupWMClass must equal it for a dock to show the entry's icon on the
# running window
window_title() {
  local t; t=$(sed -n 's/.*\.with_title("\([^"]*\)").*/\1/p' src/viz/main.roc | head -1)
  [ -n "$t" ] || { echo "::error::src/viz/main.roc sets no window title" >&2; exit 1; }
  printf '%s' "$t"
}

# the one argument an Exec value names, read the way the desktop entry
# spec reads it: first the key file's string layer (\s \n \t \r and \\ are
# its only escapes, and any other backslash pair makes the value
# unreadable, as GLib's g_key_file_get_string refuses it), then the
# quoting layer (one double-quoted argument, inside which a backslash
# escapes only " ` $ and \), then %% as a literal percent. Prints the
# argument, or fails naming the layer that refused the value.
exec_argv0() {
  V="$1" awk 'BEGIN {
    s = ENVIRON["V"]; out = ""
    for (i = 1; i <= length(s); i++) {
      c = substr(s, i, 1)
      if (c != "\\") { out = out c; continue }
      d = substr(s, ++i, 1)
      if (d == "\\") out = out "\\"
      else if (d == "s") out = out " "
      else if (d == "n") out = out "\n"
      else if (d == "t") out = out "\t"
      else if (d == "r") out = out "\r"
      else { print "key-file layer: invalid escape \\" d > "/dev/stderr"; exit 1 }
    }
    n = length(out)
    if (n < 2 || substr(out, 1, 1) != "\"" || substr(out, n, 1) != "\"") {
      print "quoting layer: not one double-quoted argument" > "/dev/stderr"; exit 1
    }
    arg = ""
    for (i = 2; i < n; i++) {
      c = substr(out, i, 1)
      if (c == "\"") { print "quoting layer: unescaped double quote" > "/dev/stderr"; exit 1 }
      if (c != "\\") { arg = arg c; continue }
      d = substr(out, ++i, 1)
      if (d == "\"" || d == "`" || d == "$" || d == "\\") arg = arg d
      else { print "quoting layer: invalid escape \\" d > "/dev/stderr"; exit 1 }
    }
    gsub(/%%/, "%", arg)
    printf "%s", arg
  }'
}

# a desktop entry with every key the menu and the dock read
check_desktop() {
  local entry kv title; entry="$(cat "$1")"
  # a substitution inside a word list would swallow window_title's exit
  title=$(window_title)
  for kv in "[Desktop Entry]" "Type=Application" "Name=Stride" "Icon=stride" "Terminal=false" "StartupWMClass=$title"; do
    grep -qxF "$kv" <<<"$entry" || { echo "::error::$1 lacks the line $kv"; exit 1; }
  done
  grep -q '^Exec=.' <<<"$entry" || { echo "::error::$1 has no Exec line"; exit 1; }
}

linux_launcher() {
  cat <<'SH'
#!/bin/sh
# step: locate
here="$(cd "$(dirname "$0")" && pwd)"
assets="$here"
# step: path
# the window runs `stride` for the CP fit, found on the PATH: the command
# in this package comes first, so the window runs its own build's. A
# desktop launch inherits a minimal PATH, so the usual install folders
# follow, for `sh`, which the zone offset runs
PATH="$here/bin:$HOME/.local/bin:/usr/local/bin:$PATH"
export PATH
# step: log
log="$HOME/.stride/seed.log"
# step: seed-fonts
# the window reads ~/.stride/fonts; seed it from the copies shipped with
# the app, copying any that are missing or differ in size, so a copy cut
# short is repaired on the next launch
if [ -d "$assets/fonts" ]; then
  if mkdir -p "$HOME/.stride/fonts" 2>/dev/null; then
    for f in "$assets"/fonts/*.ttf; do
      [ -e "$f" ] || continue
      dst="$HOME/.stride/fonts/$(basename "$f")"
      if [ ! -e "$dst" ] || [ "$(wc -c < "$f")" != "$(wc -c < "$dst")" ]; then
        cp "$f" "$dst" 2>>"$log" || echo "$(date): could not write $dst" >> "$log"
      fi
    done
  else
    echo "$(date): could not create $HOME/.stride/fonts - the window will use its fallback font" >> "$log" 2>/dev/null || true
  fi
fi
# step: seed-img
# the splash's mark and the streak flame render from ~/.stride/img,
# seeded the same way
if [ -d "$assets/img" ]; then
  if mkdir -p "$HOME/.stride/img" 2>/dev/null; then
    for f in "$assets"/img/*.png; do
      [ -e "$f" ] || continue
      dst="$HOME/.stride/img/$(basename "$f")"
      if [ ! -e "$dst" ] || [ "$(wc -c < "$f")" != "$(wc -c < "$dst")" ]; then
        cp "$f" "$dst" 2>>"$log" || echo "$(date): could not write $dst" >> "$log"
      fi
    done
  else
    echo "$(date): could not create $HOME/.stride/img - the splash and the streak chip will show text alone" >> "$log" 2>/dev/null || true
  fi
fi
# step: home
cd "$HOME"
# step: start
# the athlete's directory first: it is the window's read-write grant, which
# a home resolved at launch cannot be written into the source it is
# declared in; then the home, the launch directory a capture's status row
# names its file under
exec "$here/stride-viz" "$HOME/.stride" "$HOME"
SH
}

# the Exec line is a placeholder: install.sh writes the launcher's absolute
# path, which only the athlete's machine knows
linux_desktop_entry() {
