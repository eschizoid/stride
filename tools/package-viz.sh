DESKTOP
}

linux_install() {
  cat <<'SH'
#!/bin/sh
# puts Stride in the desktop's application menu and its command on the
# PATH, then starts it unless STRIDE_APP_START is 0: a desktop entry under
# ~/.local/share/applications that runs the launcher beside this script,
# its icon under ~/.local/share/icons/hicolor, and ~/.local/bin/stride (or
# $STRIDE_INSTALL_DIR/stride) as a link to the command in bin/. The entry
# and the link name this folder by its absolute path, so run this again
# after moving it.
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
data="${XDG_DATA_HOME:-$HOME/.local/share}"
mkdir -p "$data/applications" "$data/icons/hicolor/256x256/apps"
cp "$here/stride.png" "$data/icons/hicolor/256x256/apps/stride.png"
# an Exec value is read in two layers. The quoting layer puts a backslash
# before " ` $ and \ inside a quoted argument; the desktop file's string
# layer, read first, then needs every backslash written twice. So \ is
# written as four backslashes, " ` and $ each as two backslashes and the
# character, and % as %%
exec_arg=$(printf '%s' "$here/stride-app" | sed -e 's/\\/\\\\\\\\/g' -e 's/["`$]/\\\\&/g' -e 's/%/%%/g')
while IFS= read -r line; do
  case "$line" in
    Exec=*) printf 'Exec="%s"\n' "$exec_arg" ;;
    *) printf '%s\n' "$line" ;;
  esac
done < "$here/stride.desktop" > "$data/applications/stride.desktop.tmp"
mv "$data/applications/stride.desktop.tmp" "$data/applications/stride.desktop"
if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database "$data/applications" >/dev/null 2>&1 || true
fi
echo "stride: added to the application menu"
# the link is made when the name is free or already links into a stride-app
# package; a file there, or a link to anything else, is another install of
# the command and is kept
bindir="${STRIDE_INSTALL_DIR:-$HOME/.local/bin}"
link="$bindir/stride"
target=""
[ -L "$link" ] && target="$(readlink "$link")"
if [ -e "$link" ] && [ ! -L "$link" ]; then
  echo "stride: kept $link, the command already installed there"
else
  case "$target" in
    "" | */stride-app/bin/stride)
      mkdir -p "$bindir"
      ln -sf "$here/bin/stride" "$link"
      echo "stride: $link now runs the command in this folder" ;;
    *) echo "stride: kept $link, which links to $target" ;;
  esac
fi
case ":$PATH:" in
  *":$bindir:"*) ;;
  *) echo "stride: $bindir is not on your PATH; add it to your shell profile to run stride by name" ;;
esac
[ "${STRIDE_APP_START:-1}" = 0 ] && exit 0
exec "$here/stride-app"
SH
}

# cmd misparses labels and goto with LF line endings, so the caller writes
# this with CRLF. The steps carry the macOS launcher's names
windows_launcher() {
  cat <<'BAT'
@echo off
rem step: locate
set "here=%~dp0"
rem step: path
rem the window runs `stride` for the CP fit, found on the PATH: the
rem command in this package's bin folder comes first, so the window runs
rem its own build's. A program started from Explorer inherits the user's
rem whole PATH, so nothing else needs adding
set "PATH=%here%bin;%PATH%"
rem step: log
set "log=%USERPROFILE%\.stride\seed.log"
rem step: seed-fonts
rem the window reads %USERPROFILE%\.stride\fonts; seed it from the copies
rem shipped beside this script, copying any that are missing or differ in
rem size, so a copy cut short is repaired on the next launch
if not exist "%USERPROFILE%\.stride\fonts" mkdir "%USERPROFILE%\.stride\fonts" >nul 2>&1 || echo %date% %time%: could not create "%USERPROFILE%\.stride\fonts" - the window will use its fallback font>>"%log%" 2>nul
for %%f in ("%here%fonts\*.ttf") do call :seed "%%~ff" fonts
rem step: seed-img
rem the splash's mark and the streak flame render from
rem %USERPROFILE%\.stride\img, seeded the same way
